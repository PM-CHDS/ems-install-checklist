export type MessageKey = keyof (typeof dict)['cs'];

export function t(lang: Lang, key: MessageKey): string {
  return dict[lang][key] ?? dict.cs[key] ?? key;
}

/** A bound translator, handy in components: `const tr = translator(lang)`. */
export function translator(lang: Lang) {
  return (key: MessageKey) => t(lang, key);
}

